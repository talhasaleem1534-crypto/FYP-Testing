import type { Host } from '../execution/host';

/**
 * The "what kind of app is this?" catalog shown to the customer when they create an application.
 *
 * Coolify asks for a *build pack* (Nixpacks / Static / Dockerfile / Compose) and lets Nixpacks guess.
 * We ask a beginner-friendly question instead - "Flask? Next.js? Static HTML?" - and each answer
 * carries everything the platform needs to build that kind of app: which files must be in the repo,
 * the usual port, the usual start command and the Dockerfile to generate.
 *
 * To support a new framework, add one entry to APP_TYPES. Nothing else needs to change.
 */
export interface AppType {
  id: string;
  label: string;
  category: 'Python' | 'JavaScript' | 'Go' | 'Other';
  description: string;
  /** Port the app listens on inside the container. The customer can change it. */
  default_port: number;
  /** At least one of these must exist in the repository root, or the deploy stops with a clear message. */
  required_files: string[];
  /** Shown to the customer. Empty = the platform works it out (see startCommand). */
  default_start_command: string;
  /** Plain-English list of what the platform will do for this type. */
  steps: string[];
  /** Things the customer's repository must have / should check. */
  tips: string[];
  /** Packages we expect in requirements.txt / package.json; missing ones only produce a warning. */
  expected_packages?: string[];
  /** Builds the Dockerfile. Undefined for 'auto' (old detector) and 'dockerfile' (customer's own). */
  dockerfile?: (o: BuildContext) => string;
  /** Default start command when the customer leaves it blank. May look at the repo. */
  startCommand?: (o: BuildContext) => string;
}

/** What prepareBuild found in the repository, handed to the recipes (they never touch files themselves). */
export interface BuildContext {
  port: number;
  start: string;
  /** Parsed package.json, if the repo has one. */
  pkg: any | null;
  /** Django project folder (the one holding wsgi.py), if found. */
  djangoProject: string | null;
}

/** Name of the file we generate. Separate from the customer's own `Dockerfile`, so we never overwrite theirs. */
export const GENERATED_DOCKERFILE = 'Dockerfile.deploystack';

const HEADER = '# Auto-generated by DeployStack PaaS';

/** Run the start command through sh so $PORT etc. are expanded. JSON-quoted, so it stays one argument. */
const shellCmd = (start: string) => `CMD ["sh", "-c", ${JSON.stringify(start)}]`;

const pythonDockerfile = (extraPip: string) => ({ port, start }: BuildContext) => `${HEADER}
FROM python:3.12-slim
WORKDIR /app
ENV PYTHONUNBUFFERED=1 PORT=${port}
COPY requirements.txt .
RUN pip install --no-cache-dir -r requirements.txt${extraPip ? ` && pip install --no-cache-dir ${extraPip}` : ''}
COPY . .
EXPOSE ${port}
${shellCmd(start)}`;

/** Find the Django project folder (the one holding wsgi.py next to manage.py), e.g. "mysite". */
export async function findDjangoProject(host: Host, repoDir: string): Promise<string | null> {
  try {
    for (const entry of await host.listDir(repoDir)) {
      if (entry.dir && (await host.exists(host.join(repoDir, entry.name, 'wsgi.py')))) return entry.name;
    }
  } catch { /* unreadable repo: fall through */ }
  return null;
}

