export const APP_TYPE_IDS = APP_TYPES.map(t => t.id);

export function getAppType(id: string | undefined): AppType {
  return APP_TYPES.find(t => t.id === id) || APP_TYPES[0];
}

/** What the API returns: the catalog without the build functions. */
export function publicAppTypes() {
  return APP_TYPES.map(({ dockerfile, startCommand, ...rest }) => rest);
}

export interface BuildPlan {
  ok: boolean;
  /** Dockerfile to build with (when ok). */
  dockerfile?: string;
  /** What to tell the customer (when not ok). */
  error?: string;
  messages: string[];
}

/**
 * Check the checkout has what this app type needs, then write the Dockerfile for it.
 * Works on this machine or on a server over SSH (all file access goes through `host`).
 * Returns which Dockerfile to build with, or a beginner-friendly error.
 * Not used for 'auto' (the old detector handles that).
 */
export async function prepareBuild(type: AppType, host: Host, repoDir: string, port: number, startOverride?: string): Promise<BuildPlan> {
  const messages: string[] = [];
  const at = (f: string) => host.join(repoDir, f);
  const present = new Set<string>();
  for (const f of new Set([...type.required_files, 'requirements.txt', 'package.json', 'Dockerfile'])) {
    if (await host.exists(at(f))) present.add(f);
  }
  const has = (f: string) => present.has(f);

  if (type.required_files.length && !type.required_files.some(has)) {
    return {
      ok: false,
      messages,
      error: `${type.label} apps need ${type.required_files.join(' or ')} in the repository root, but it was not found. ` +
        `Add it, or create the app again with a different app type.`,
    };
  }
  // Django needs both manage.py (checked above) and requirements.txt.
  if (type.id === 'django' && !has('requirements.txt')) {
    return { ok: false, messages, error: 'Django apps need a requirements.txt in the repository root (run: pip freeze > requirements.txt).' };
  }
  messages.push(`✅ Found ${type.required_files.filter(has).join(', ')}`);

  const read = async (f: string) => (has(f) ? host.readFile(at(f)).catch(() => '') : '');
  const pkgText = await read('package.json');
  let pkg: any = null;
  try { pkg = pkgText ? JSON.parse(pkgText) : null; } catch { messages.push('⚠️  package.json is not valid JSON.'); }

  if (type.expected_packages?.length) {
    const manifest = `${await read('requirements.txt')}\n${pkgText}`.toLowerCase();
    const missing = type.expected_packages.filter(p => !manifest.includes(p));
    if (missing.length) messages.push(`⚠️  ${missing.join(', ')} not found in your dependencies - the build may fail.`);
  }

  if (!type.dockerfile) {
    messages.push('📄 Using your own Dockerfile.');
    return { ok: true, dockerfile: 'Dockerfile', messages };
  }

  const ctx: BuildContext = {
    port, pkg, start: '',
    djangoProject: type.id === 'django' ? await findDjangoProject(host, repoDir) : null,
  };
  ctx.start = (startOverride || '').trim() || type.startCommand?.(ctx) || type.default_start_command;
  await host.writeFile(at(GENERATED_DOCKERFILE), type.dockerfile(ctx));
  messages.push(`📝 Generated ${GENERATED_DOCKERFILE} for ${type.label} (port ${port}${ctx.start ? `, start: ${ctx.start}` : ''}).`);
  if (has('Dockerfile')) messages.push(`ℹ️  Your repository also has a Dockerfile. It is ignored because you chose "${type.label}".`);
  return { ok: true, dockerfile: GENERATED_DOCKERFILE, messages };
}
